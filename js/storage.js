let sessions = JSON.parse(localStorage.getItem('sneh_sessions')) || {};
let tempSessions = {};
let currentSessionId = localStorage.getItem('sneh_current_session') || null;
let currentSessionIsIncognito = false;
let pendingIncognito = false;

let userProfile = JSON.parse(localStorage.getItem('sneh_user_profile')) || null;

// ========== AUTH PROFILE ==========
export function getUserProfile() {
  return userProfile;
}

export function setUserProfile(profile) {
  userProfile = profile;
  if (profile) {
    localStorage.setItem('sneh_user_profile', JSON.stringify(profile));
  } else {
    localStorage.removeItem('sneh_user_profile');
  }
}

export function logoutUser() {
  setUserProfile(null);
}

// ========== SESSION MANAGEMENT ==========
function loadSessions() {
  sessions = JSON.parse(localStorage.getItem('sneh_sessions')) || {};
}

function saveSessions(depth = 0) {
  if (depth > 3) {
    console.error("Storage critically full. Could not recover.");
    return;
  }
  try {
    localStorage.setItem('sneh_sessions', JSON.stringify(sessions));
    localStorage.setItem('sneh_current_session', currentSessionId);
  } catch (e) {
    if (e.name === 'QuotaExceededError' || e.name === 'NS_ERROR_DOM_QUOTA_REACHED') {
      console.warn("Storage full. Attempting to delete oldest chat...");
      const sortedIds = Object.keys(sessions).sort((a, b) => a.split('_')[1] - b.split('_')[1]);
      if (sortedIds.length > 1) {
        delete sessions[sortedIds[0]];
        saveSessions(depth + 1);
      } else {
        alert("Snèh AI: Your local chat memory is full. Please delete some chats.");
      }
    } else {
      console.error("Error saving sessions:", e);
    }
  }
}

