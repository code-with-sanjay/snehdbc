export function createNewChat() {
  currentSessionId = 'chat_' + Date.now();
  currentSessionIsIncognito = false;
  sessions[currentSessionId] = [{ role: "system", content: HARDENED_SYSTEM_PROMPT }];
  saveSessions();
  return sessions[currentSessionId];
}

export function createIncognitoChat() {
  currentSessionId = 'incognito_' + Date.now();
  currentSessionIsIncognito = true;
  tempSessions[currentSessionId] = [{ role: "system", content: HARDENED_SYSTEM_PROMPT }];
  return tempSessions[currentSessionId];
}

export function saveAndRefresh() {
  if (!currentSessionIsIncognito) {
    saveSessions();
  }
}

export function deleteChat(id) {
  if (sessions[id]) {
    delete sessions[id];
    if (currentSessionId === id && !currentSessionIsIncognito) {
      currentSessionId = null;
      currentSessionIsIncognito = false;
    }
    saveSessions();
    if (!currentSessionId) createNewChat();
  } else if (tempSessions[id]) {
    delete tempSessions[id];
    if (currentSessionId === id && currentSessionIsIncognito) {
      currentSessionId = null;
      currentSessionIsIncognito = false;
      createNewChat();
    }
  }
}

export function loadChat(id) {
  currentSessionId = id;
  currentSessionIsIncognito = !!tempSessions[id];
  saveSessions();
}

export function getCurrentMessages() {
  if (currentSessionIsIncognito) {
    return tempSessions[currentSessionId] || [];
  }
  return sessions[currentSessionId] || [];
}

export function pushMessageToCurrent(role, content) {
  const messages = getCurrentMessages();
  messages.push({ role, content });
  if (!currentSessionIsIncognito) {
    saveSessions();
  }
}

export function getPendingIncognito() {
  return pendingIncognito;
}

export function setPendingIncognito(value) {
  pendingIncognito = value;
}

